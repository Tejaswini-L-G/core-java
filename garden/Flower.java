
public class Flower {
    int flowerId;
    String name;
    String color;
    double price;
    boolean fragrance;

    public Flower(){}

    public Flower(int flowerId,String name,String color,double price,boolean fragrance){
        this.flowerId=flowerId;
        this.name=name;
        this.color=color;
        this.price=price;
        this.fragrance=fragrance;
    }
}
