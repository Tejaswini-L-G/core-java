
public class Flavour {

    int flavourId;
    String name;
    String brand;
    double price;
    boolean sugarFree;

    public Flavour(){}

    public Flavour(int flavourId,String name,String brand,double price,boolean sugarFree){
        this.flavourId=flavourId;
        this.name=name;
        this.brand=brand;
        this.price=price;
        this.sugarFree=sugarFree;
    }
}
