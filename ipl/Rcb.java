
public class Rcb {

    int playerId;
    String name;
    String role;
    int jerseyNumber;
    boolean playing;

    public Rcb(){}

    public Rcb(int playerId,String name,String role,int jerseyNumber,boolean playing){
        this.playerId=playerId;
        this.name=name;
        this.role=role;
        this.jerseyNumber=jerseyNumber;
        this.playing=playing;
    }
}
