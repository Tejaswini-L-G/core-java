
public class Cop {
    int copId;
    String name;
    String shift;
    int experience;
    String location;

    public Cop(){}

    public Cop(int copId,String name,String shift,int experience,String location){
        this.copId=copId;
        this.name=name;
        this.shift=shift;
        this.experience=experience;
        this.location=location;
    }
}
